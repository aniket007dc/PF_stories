#!/usr/bin/env python3
"""Generate an episode's prompt files from episode.json and the brand folder.

  prompts-writing.md   steps 3 and 4: the script prompt and the shot prompt, filled in
  prompts.md           steps 5 and 6: setup, assets, and every shot's keyframe and motion prompts

Never edit those two files by hand. Change episode.json (or brand/), then run:

  python3 tools/build_prompts.py                              every episode
  python3 tools/build_prompts.py episodes/ep01-claim-reject    one episode
  python3 tools/build_prompts.py --check                      fail if a file is out of date (used by CI)
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dc  # noqa: E402

HEADER = ("<!-- Generated by tools/build_prompts.py from episode.json and brand/. "
          "Don't edit by hand: change episode.json, then run python3 tools/build_prompts.py -->\n")


def fence(text):
    return "```text\n" + text.strip() + "\n```"


def mmss(seconds):
    seconds = int(round(seconds))
    return "{}:{:02d}".format(seconds // 60, seconds % 60)


def is_build(ep_dir):
    """Built by tools/build_reel.py: the episode has a reel.json, or says "route": "build"."""
    if (Path(ep_dir) / "reel.json").exists():
        return True
    try:
        return dc.load_json(Path(ep_dir) / "episode.json").get("route") == "build"
    except Exception:  # noqa: BLE001
        return False


def routes(ep_dir=None):
    if ep_dir is not None and is_build(ep_dir):
        # The episode has a build file: tools/build_reel.py draws every word, so nothing depends on Muse's models
        return "build", "build"
    cap = dc.load_json(dc.BRAND_DIR / "capabilities.json").get("results", {})
    if cap.get("code_render") == "yes":
        # Text drawn with real fonts beats any model: exact by construction
        return "code", "code"
    keyframe ="muse-text" if cap.get("image_text_exact") == "yes" and cap.get("image_edit_keeps_background") == "yes" else "clean-plate"
    motion = "muse" if cap.get("motion_keeps_text") == "yes" and cap.get("image_to_video") == "yes" else "canva"
    return keyframe, motion


def data_sheet(ep):
    lines = []
    for it in ep.get("data", []):
        extra = ""
        if it.get("kind") == "rule":
            lines.append("- {}: {} (rule, from {})".format(it["id"], dc.display(it), it.get("source", "its source")))
            continue
        if it.get("kind") == "derived":
            extra = ": " + it.get("formula", "")
        elif it.get("kind") == "assumption":
            extra = ": say 'maan lo' or show EXAMPLE the first time"
        lines.append("- {} = {} ({}{}) · {}".format(it["id"], dc.display(it), it.get("kind"), extra, it.get("label", "")))
    return "\n".join(lines)


def forms_sheet():
    """The EPFO forms a reel may name (brand/epfo-forms.json), one per line."""
    forms = dc.epfo_forms()
    return "\n".join("- Form {}: {}".format(fid, f.get("for", "")) for fid, f in forms.items()) or "[no forms listed yet]"


def focus_fields(text, ep):
    """The Focus prompts' lists: the chapters' labels, the screen parts and overlays the build draws (tools/screens.py),
    its icons, and how fresh the sources must be."""
    b = dc.for_style(dc.brand(), ep)
    rules = b.get("rules") or {}
    parts = ", ".join("{} ({})".format(k, v) for k, v in (b.get("parts") or {}).items())
    text = text.replace("{{PARTS}}", parts).replace("{{SOURCE_DAYS}}", str(rules.get("source_days") or 60)).replace(
        "{{SEEN_DAYS}}", str(rules.get("seen_days") or 30))
    if "{{PART_KINDS}}" in text or "{{OVERLAY_KINDS}}" in text or "{{ICONS}}" in text:
        import screens                                  # tools/screens.py: what the build can draw (needs Pillow)
        text = text.replace("{{PART_KINDS}}", "\n".join("  - {}: {}\n    {}".format(k, about, example)
                                                        for k, (example, about) in screens.PART_DOCS.items()))
        text = text.replace("{{OVERLAY_KINDS}}", "\n".join("  - {}: {}\n    {}".format(k, about, example)
                                                           for k, (example, about) in screens.OVERLAY_DOCS.items()))
        text = text.replace("{{ICONS}}", ", ".join(screens.ICONS))
    return text


def render_writing(ep_dir):
    ep = dc.load_json(ep_dir / "episode.json")
    brief = ep.get("brief", {})
    out = [HEADER, "# Writing prompts · {} · {}".format(ep.get("id"), ep.get("title")), ""]
    if is_build(ep_dir):
        out.append("The two writing steps of a new episode (MUSE.md → A new episode). Follow each prompt, put the answer "
                   "into the files it names, upload them, and GitHub checks every number and word.")
    else:
        out.append("Use these in steps 3 and 4. Paste the reply into `episode.json`, then run `python3 tools/validate.py episodes/{}`.".format(
            ep_dir.name))
    out.append("")
    out.append("## Step 3 · Script prompt")
    out.append("")
    focus = ep.get("style") == "focus"
    if focus:
        out.append("**Theme: Focus** (`\"style\": \"focus\"`): how to do one EPFO task on the screen itself, the "
                   "screens drawn from the newest official pages and videos (styles/focus/STYLE.md).")
        out.append("")
    writer = dc.prompt_text("focus-script-writer.txt" if focus else "script-writer.txt")
    writer = (focus_fields(writer, ep) if focus else writer).replace("{{EPISODE}}", ep_dir.name).replace(
        "{{TOPIC}}", brief.get("topic", "[TOPIC]")).replace(
        "{{VIEWER}}", brief.get("viewer", "[VIEWER]")).replace("{{DATA_SHEET}}", data_sheet(ep) or "[no data yet: finish step 2 first]").replace(
        "{{FORMS}}", forms_sheet())
    out.append(fence(writer))
    out.append("")
    if is_build(ep_dir):
        out.append("## Step 4 · Shots and reel.json prompt")
        out.append("")
        out.append("Put `shots` and `breaks` into `episode.json`, and `reel` into `reel.json` (adding "
                   "`\"schema\": \"dc-reel/1\"`, `\"episode\": \"{}\"` and `\"brand_label\": \"{}\"` at the top).".format(
                       ep_dir.name, dc.brand().get("brand", "").upper()))
        out.append("")
    else:
        out.append("## Step 4 · Shot prompt")
        out.append("")
    if ep.get("script"):
        script = [{"shot": l.get("shot"), "chapter": l.get("chapter"), "vo": l.get("vo"), "highlights": l.get("highlights", []),
                   "uses": l.get("uses") or next((s.get("uses", []) for s in ep.get("shots", []) if s.get("id") == l.get("shot")), [])}
                  for l in ep["script"]]
        if is_build(ep_dir):
            writer4 = (focus_fields(dc.prompt_text("focus-reel-writer.txt"), ep) if focus else
                       dc.prompt_text("reel-writer.txt")).replace("{{EPISODE}}", ep_dir.name).replace(
                "{{SCRIPT_JSON}}", json.dumps(script, ensure_ascii=False, indent=1)).replace(
                "{{DATA_SHEET}}", data_sheet(ep) or "[no data yet]")
        else:
            writer4 = dc.prompt_text("shot-writer.txt").replace("{{STYLE_LOCK}}", dc.prompt_text("style-lock.txt")).replace(
                "{{SCRIPT_JSON}}", json.dumps(script, ensure_ascii=False, indent=1))
        out.append(fence(writer4))
    else:
        out.append("The script isn't written yet. Finish step 3 first.")
    out.append("")
    return "\n".join(out)


ELEMENT_NAMES = {"card": "card", "stamp": "stamp", "photo": "photo", "headline": "headline", "note": "handwritten note",
                 "tag": "tag", "funnel": "funnel chart", "line_chart": "line chart", "arrow_card": "arrow card",
                 "timeline": "timeline bar", "typewriter": "typewriter card", "endcard": "end card",
                 "screen": "screenshot"}


