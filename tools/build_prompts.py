def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("episodes", nargs="*")
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    args = ap.parse_args()
    stale = []
    for ep_dir in dc.episode_dirs(args.episodes):
        for name, fn in (("prompts.md", render), ("prompts-writing.md", render_writing)):
            fresh = fn(ep_dir)
            path = ep_dir / name
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if args.check:
                if current != fresh:
                    stale.append(dc.rel(path))
            elif current != fresh:
                path.write_text(fresh, encoding="utf-8")
                print("wrote", dc.rel(path))
    if args.check:
        if stale:
            print("Out of date (run python3 tools/build_prompts.py):\n  " + "\n  ".join(stale))
            sys.exit(1)
        print("Prompt files are up to date.")


if __name__ == "__main__":
    main()
